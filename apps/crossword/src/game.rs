use std::collections::VecDeque;

pub const HISTORY: usize = 32;
pub struct Puzzle {
    pub id: &'static str,
    pub title: &'static str,
    pub level: &'static str,
    pub side: usize,
    pub answer: &'static [u8],
    pub across: &'static [&'static str],
    pub down: &'static [&'static str],
}
/// One numbered entry in a grid: where it starts, which way it reads, and how
/// many squares it covers.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Entry {
    pub number: usize,
    pub down: bool,
    pub first: usize,
    pub length: usize,
}

