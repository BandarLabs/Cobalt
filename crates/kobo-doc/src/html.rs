//! Reading HTML as a document.
//!
//! # Why not [`kobo_html::to_text`]
//!
//! That function exists for a Hacker News comment: a short fragment where the
//! only structure worth keeping is where the paragraphs are. It caps its
//! output at eight kilobytes and flattens everything else, and both are right
//! for a comment.
//!
//! A book is neither short nor flat. A chapter of a book is a heading and the
//! prose under it, and losing the heading loses the chapter, which is what
//! the table of contents is made of and what "next chapter" moves between. So
//! this is a second scanner over the same syntax, keeping the part the other
//! one throws away, and sharing the entity table and the attribute reader so
//! that the two cannot disagree about what `&rsquo;` is.
//!
//! # What it is not
//!
//! Not a compliant HTML parser. There is no tree, no implied end tags, no
//! error recovery algorithm, no `<table>` reconstruction. It is a scan over
//! the tags looking for the dozen elements that change what a run of text
//! *is*, and everything else is stripped and its contents kept. That is
//! enough for EPUB (which is XHTML, and generated by a tool) and enough for
//! a saved web page, and it cannot get stuck, recurse or allocate a tree.

use std::collections::BTreeMap;

use kobo_html::{attribute, decode_entities, element_name, skip_element};

use crate::{
    Block, BlockStyle, Builder, Document, InlineSpan, InlineStyle, RichBlock, TextAlignment,
    MAX_BLOCK_TEXT,
};

/// Elements whose contents are instructions rather than words.
const OPAQUE: [&str; 3] = ["script", "style", "iframe"];

/// Elements that carry their own reading in an attribute.
///
/// A drawing has no text in it, and what a converter can say about one is
/// whatever the document said it showed.
///
/// `MathML` used to be in here too, and it was a mistake. The `alttext` a
/// renderer writes is the LaTeX *source*, and putting source on a page is not
/// a rendering of the formula, it is a picture of somebody else's keyboard:
/// `\mathbb{R}^{k}\to\{\pm 1\}` in the middle of an English sentence.
/// Formulae now go through [`kobo_html::math`], which reads the presentation
/// markup the source was rendered into.
const ALT_TEXT: [&str; 1] = ["svg"];

/// Reads an HTML document.
#[must_use]
pub fn parse(source: &str) -> Document {
    parse_with_css(source, "")
}

/// Reads HTML with a bounded safe subset of publisher CSS.
#[must_use]
pub fn parse_with_css(source: &str, external_css: &str) -> Document {
    parse_within(source, external_css, Allowance::whole())
}

/// How many formulae a document may still be given pictures for.
///
/// A count and no clock. There used to be a clock too, and it was the one
/// that mattered: the parser drew each formula as it met it, which is 4.7 ms
/// apiece on a Clara BW inside a callback the runtime allows 250 ms. Drawing
/// happens in the picture pipeline now, so nothing here spends time on a
/// formula beyond noting that there is one, and the only question left is how
/// many pictures are worth holding.
#[derive(Clone, Copy)]
pub struct Allowance {
    /// How many more formulae may be given pictures.
    pub pictures: usize,
}

impl Allowance {
    /// A whole document's worth.
    #[must_use]
    pub const fn whole() -> Self {
        Self {
            pictures: crate::MAX_FORMULA_PICTURES,
        }
    }

    /// Whether there is room for one more formula.
    const fn open(self, taken: usize) -> bool {
        taken < self.pictures
    }
}

/// The same, for one file of a book that has a budget to share.
///
/// A book's chapters are read one at a time, and a limit applied to each of
/// them separately is not a limit on the book: thirty chapters allowed
/// sixty-four formulae apiece is nineteen hundred, which is the number the
/// limit exists to prevent. The clock is shared for the same reason -- a
/// budget spent afresh on every chapter is thirty times the budget.
#[must_use]
pub fn parse_within(source: &str, external_css: &str, allowance: Allowance) -> Document {
    let mut take = external_css.len().min(MAX_CSS_BYTES);
    while !external_css.is_char_boundary(take) {
        take -= 1;
    }
    let mut css = external_css[..take].to_owned();
    let embedded = embedded_styles(source);
    let mut remaining = embedded.len().min(MAX_CSS_BYTES.saturating_sub(css.len()));
    while !embedded.is_char_boundary(remaining) {
        remaining -= 1;
    }
    css.push_str(&embedded[..remaining]);
    let mut state = State::new(StyleSheet::parse(&css), allowance);
    let mut rest = source;
    while let Some(at) = rest.find('<') {
        state.words(&rest[..at]);
        let tail = &rest[at..];

        // A comment or a CDATA section may contain a `>` that does not end it.
        // Searching for the plain `>` first would cut inside one and spill the
        // remainder onto the panel.
        if let Some(after) = skip_bracketed(tail) {
            rest = after;
            continue;
        }

        let Some(end) = tail.find('>') else {
            // A `<` that never closes is not a tag. It is the character it is,
            // and reading it as an unterminated tag would silently drop
            // everything after it.
            state.words(tail);
            rest = "";
            break;
        };
        let inside = &tail[1..end];
        rest = &tail[end + 1..];

        let name = element_name(inside);
        let closing = inside.starts_with('/');
        if !closing && name == "math" {
            // The whole element, opening tag included, because the renderer
            // reads the tree rather than the text: the children are the
            // symbols and the structure between them is the formula.
            let after = skip_element(rest, &name);
            let taken = rest.len().saturating_sub(after.len());
            let element = &tail[..(end + 1).saturating_add(taken)];
            let drawn = kobo_html::math::render(element);
            // Inside an equation row every piece of it is one formula, and
            // the pieces are set together rather than one at a time.
            if state.equation.is_some() {
                state.equation_piece(attribute(inside, "alttext").unwrap_or_default(), &drawn);
                rest = after;
                continue;
            }
            if state.display_formula(inside, &drawn) {
                rest = after;
                continue;
            }
            if !drawn.is_empty() {
                // Spaced on both sides because an equation sits inside a
                // sentence, and the tags either side of it carry no
                // whitespace of their own.
                state.words(" ");
                if !state.inline_formula(inside, &drawn) {
                    state.words(&drawn);
                }
                // Except where a mark of punctuation follows, which is set
                // tight against whatever it ends. `LaTeXML` writes the comma
                // straight onto the closing tag -- `</math>, we randomly` --
                // so the space put here was one nothing in the document asked
                // for: seventy lines of a 163-page paper read "the split
                // 𝒯⁽ʲ⁾ . We write" and "0.91 , an absolute gain".
                if !punctuation_follows(after) {
                    state.words(" ");
                }
            }
            rest = after;
            continue;
        }
        if !closing && ALT_TEXT.contains(&name.as_str()) {
            // Read from the attribute, never from the children: the point is
            // that the children are notation and the attribute is the reading
            // of it. An element with neither is skipped in silence, which is
            // what a picture with no caption gets too.
            for spelling in ["alttext", "aria-label", "title"] {
                let Some(text) = attribute(inside, spelling).map(str::trim) else {
                    continue;
                };
                if !text.is_empty() {
                    // Spaced on both sides because an equation sits inside a
                    // sentence, and the tags either side of it carry no
                    // whitespace of their own.
                    state.words(" ");
                    state.words(text);
                    state.words(" ");
                    break;
                }
            }
            rest = skip_element(rest, &name);
            continue;
        }
        if !closing && OPAQUE.contains(&name.as_str()) {
            rest = skip_element(rest, &name);
            continue;
        }
        if closing {
            state.close(&name);
        } else {
            state.open(&name, inside);
        }
    }
    state.words(rest);
    state.finish()
}

/// Whether a row of groups belongs to the row of column names under it.
///
/// A group covers several columns and is written in the first of them, so its
/// row has fewer cells filled than the row beneath. One cell reaching across
/// a whole table is a title somebody drew with a row rather than a set of
/// groups, and keeps a row of its own.
fn heads_the_row_below(groups: &[String], names: &[String]) -> bool {
    let filled = |cells: &[String]| cells.iter().filter(|cell| !cell.trim().is_empty()).count();
    filled(groups) >= 2 && filled(groups) < filled(names)
}

/// Joins a row of group headings to the row that names the columns under it.
///
/// The names win; the groups fill the columns the names left empty, which is
/// the column a group heading reached down over rather than across. So
/// `Tokenizer` over a blank, and `Fidelity` over `rFID`, come out as
/// `Tokenizer` and `rFID`: one heading for each column, which is what
/// everything reading a table downstream is written for.
///
/// The groups are not kept beside the names. `Multimodal Learnability Text`
/// is a column heading no panel this size can set, and the caption under a
/// results table says what the groups were.
fn join_headings(groups: Row, names: Row) -> Row {
    let mut cells = names.cells;
    for (column, group) in groups.cells.into_iter().enumerate() {
        match cells.get_mut(column) {
            Some(cell) if cell.trim().is_empty() => *cell = group,
            Some(_) => {}
            None => cells.push(group),
        }
    }
    Row {
        cells,
        header: true,
        ..Row::default()
    }
}

/// Whether a string is a number a paper would label an equation with.
///
/// `(1)`, `(2.3)`, `(A.1)`. Deliberately narrow: this is checked because the
/// text is about to be handed to a typesetter as part of the formula, and the
/// margin of an equation row is somewhere a document can put anything at all.
fn is_equation_tag(number: &str) -> bool {
    let Some(inner) = number
        .strip_prefix('(')
        .and_then(|rest| rest.strip_suffix(')'))
    else {
        return false;
    };
    !inner.is_empty()
        && inner.len() <= 12
        && inner
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '.')
}

/// The classes an element was given, or nothing when it was given none.
fn class_of(inside: &str) -> &str {
    attribute(inside, "class").unwrap_or_default()
}

/// Whether the next thing a reader will see binds to what came before it.
///
/// Only ever asked about the space after a formula. Tags are stepped over,
/// because the mark may sit outside a span the formula was wrapped in, and so
/// is whitespace: a document that wrote a space in front of its own comma
/// still meant the comma to be set against the word, and a formula is a word.
///
/// Looking past the end of a block can at worst drop a space that was going to
/// be trimmed off the end of it anyway.
fn punctuation_follows(after: &str) -> bool {
    const BINDS: [char; 11] = [
        ',', '.', ';', ':', '!', '?', ')', ']', '}', '\u{2019}', '\u{201d}',
    ];
    let mut rest = after;
    loop {
        rest = rest.trim_start();
        if rest.starts_with('<') {
            if let Some(after_bracket) = skip_bracketed(rest) {
                rest = after_bracket;
                continue;
            }
            let Some(end) = rest.find('>') else {
                return false;
            };
            rest = &rest[end + 1..];
            continue;
        }
        return rest.starts_with(BINDS);
    }
}

const MAX_CSS_BYTES: usize = 256 * 1024;
const MAX_CSS_RULES: usize = 4_096;

/// Skips a comment, a doctype or a CDATA section, if `tail` begins with one.
pub(crate) fn skip_bracketed(tail: &str) -> Option<&str> {
    for (opens, closes) in [("<!--", "-->"), ("<![CDATA[", "]]>")] {
        if let Some(body) = tail.strip_prefix(opens) {
            // An unterminated comment takes the rest of the file. That is the
            // safe direction: the alternative is drawing markup somebody left
            // half-written.
            return Some(
                body.find(closes)
                    .map_or("", |at| &body[at + closes.len()..]),
            );
        }
    }
    None
}

/// A note body whose text is being kept out of the paragraph around it.
struct OpenNote {
    tag: String,
    depth: usize,
    text_from: usize,
    spans_from: usize,
    /// Whether the words are worth setting again once they are out.
    keep: bool,
}

/// How many footnotes one paragraph may hang off itself.
///
/// A paragraph with more notes than sentences is a generator misfiring, not
/// scholarship, and the rest are left where they were written.
const MAX_HOISTED_NOTES: usize = 16;

/// How long a list mark may be before it is prose wearing a mark's clothes.
const MAX_MARK: usize = 12;

/// Whether an element is the body of a footnote rather than its mark.
///
/// There is no element for this: HTML has never had one, so every generator
/// spells it with a class. These are the two spellings that reach a reader in
/// practice -- `LaTeXML`'s, which is what an arXiv paper is written in, and the
/// plain word, which is what everything else uses.
fn is_a_note_body(inside: &str) -> bool {
    has_class(inside, &["ltx_note_outer", "footnote-body"])
}

/// Whether an element is a mark the generator drew for a list itself.
///
/// A generator with no list to hand writes the bullet or the number out as
/// text beside the item. A reader has a list, and draws its own: left in, the
/// generator's mark is read as an item of its own with nothing in it, and the
/// words it was supposed to mark are set as ordinary prose with no mark at
/// all. So the mark comes out and the item keeps its own.
fn is_a_generators_own_mark(inside: &str) -> bool {
    has_class(inside, &["ltx_tag_item", "ltx_tag_note"])
}

fn has_class(inside: &str, wanted: &[&str]) -> bool {
    attribute(inside, "class").is_some_and(|classes| {
        classes.split_whitespace().any(|class| {
            wanted
                .iter()
                .any(|candidate| class.eq_ignore_ascii_case(candidate))
        })
    })
}

struct State {
    builder: Builder,
    text: String,
    spans: Vec<InlineSpan>,
    inline: InlineStyle,
    inline_stack: Vec<(String, InlineStyle)>,
    block_style: BlockStyle,
    block_stack: Vec<(String, BlockStyle)>,
    stylesheet: StyleSheet,
    /// The link being read: where it points, and how much text had been
    /// collected when it opened, so its own words can be taken back out.
    link: Option<(String, usize)>,
    /// How many block quotations deep the scan is. See `markdown` for why this
    /// is a count.
    quoted: usize,
    /// How many `<pre>` elements deep the scan is.
    ///
    /// Inside one, the line breaks are the content and no tag rearranges
    /// anything, so the whole of it is collected as written.
    pre: usize,
    /// Whether each open list is numbered, innermost last.
    lists: Vec<bool>,
    heading: Option<u8>,
    item: bool,
    caption: bool,
    /// Whether the words being collected are the document's title rather than
    /// something to draw.
    titling: bool,
    /// The LaTeX of each formula met so far, keyed by the name the block or
    /// run referring to it uses.
    ///
    /// The source, not a picture: what to draw rather than the drawing, so
    /// that the parse costs a formula nothing but the note of it.
    formulae: BTreeMap<String, String>,
    /// How many more formulae this file may name.
    allowance: Allowance,
    /// The displayed equation being read, once an equation row has opened one.
    equation: Option<Equation>,
    /// The table row being read, once `<tr>` has opened one.
    ///
    /// A cell's words are collected by the same machinery as a paragraph's
    /// and taken out again when the cell closes, so everything that already
    /// worked inside prose -- entities, inline tags, links -- works inside a
    /// cell without a second implementation of any of it.
    row: Option<Row>,
    /// How many further rows each column of the open table is still covered
    /// for by a cell above it.
    ///
    /// A results table heads its first column once and lets it reach down
    /// over the row that names the rest: `Tokenizer` is written with
    /// `rowspan="2"`, so the row under it has no cell for that column at all.
    /// Counted as one cell each, every heading below moved a column left and
    /// the values came out labelled with their neighbour's name.
    covered: Vec<usize>,
    /// A row of group headings held back to be joined to the row that names
    /// the columns under it.
    ///
    /// A results table heads itself twice, `Multimodal Learnability` written
    /// once over the three columns called `Text`, `I2T` and `T2I`. Both rows
    /// are headings, and everything downstream -- which row names the
    /// columns, which rows to skip when the table is too wide to draw as one
    /// -- is written for tables that head themselves once. They are joined
    /// here, where the spans that say which row is which have just been read,
    /// rather than guessed at again from the words further along.
    held: Option<Row>,
    /// How many rows of the open table have been pushed.
    rows_seen: usize,
    /// The footnote body currently being read out of the running text.
    note: Option<OpenNote>,
    /// Footnotes lifted out of the paragraph being built, to be set after it.
    notes: Vec<(String, Vec<InlineSpan>)>,
    /// A list mark taken out of one block, waiting to lead the next.
    mark: Option<String>,
}

/// A displayed equation part way through being read out of its table.
///
/// An `align` environment sets one equation across several cells -- the left
/// side in one, the relation and right side in the next -- so the pieces are
/// gathered here and set as the single formula they are.
#[derive(Default)]
struct Equation {
    /// The LaTeX of each piece, in the order the row sets them.
    latex: String,
    /// The line of text the same pieces read as, for a reader whose build
    /// cannot draw or whose picture has not arrived.
    drawn: String,
    /// The number the paper gives the equation, when it numbers one.
    number: String,
}

/// How many columns one cell may claim to span.
///
/// A paper's widest grouped header covers half a dozen; the bound is here
/// because the number is written in the document and is otherwise a way to
/// ask for a row of a million empty cells.
const MAX_CELL_SPAN: usize = 32;

/// A table row part way through being read.
#[derive(Default)]
struct Row {
    cells: Vec<String>,
    /// Set by the first `th` in the row. A row of headings names the columns
    /// and is drawn differently from one that fills them.
    header: bool,
    /// Whether a cell is open, so that the words collected since belong to it
    /// rather than to the row's stray text.
    open: bool,
    /// How many columns the open cell covers.
    ///
    /// One for almost every cell. A grouped header is the exception and the
    /// reason this is here: a results table writes `Multimodal Learnability`
    /// once over the three columns it names, and a row that counted it as one
    /// cell came out three columns short of every row below it.
    span: usize,
    /// How many rows down the open cell reaches.
    down: usize,
    /// Whether any cell in this row covered more than its own square.
    spanned: bool,
}

impl State {
    fn new(stylesheet: StyleSheet, allowance: Allowance) -> Self {
        Self {
            builder: Builder::new(),
            equation: None,
            formulae: BTreeMap::new(),
            allowance,
            link: None,
            text: String::new(),
            spans: Vec::new(),
            inline: InlineStyle::default(),
            inline_stack: Vec::new(),
            block_style: BlockStyle::default(),
            block_stack: Vec::new(),
            stylesheet,
            quoted: 0,
            pre: 0,
            lists: Vec::new(),
            heading: None,
            item: false,
            caption: false,
            titling: false,
            row: None,
            covered: Vec::new(),
            held: None,
            rows_seen: 0,
            note: None,
            notes: Vec::new(),
            mark: None,
        }
    }

    /// Adds a run of literal text.
    fn words(&mut self, text: &str) {
        if text.is_empty() {
            // Two adjacent tags, which is most of an EPUB.
            return;
        }
        // The only words in an equation row are the number in its margin.
        // Kept apart from the formula so that "(1)" is not read as part of
        // the mathematics, and so that it survives being drawn as a picture.
        if let Some(equation) = &mut self.equation {
            let decoded = decode_entities(text);
            let number = decoded.trim();
            if !number.is_empty() {
                if !equation.number.is_empty() {
                    equation.number.push(' ');
                }
                equation.number.push_str(number);
            }
            return;
        }
        // A document with no block-level tags at all is one paragraph as long
        // as the file. The block ceiling would cut it on the way out, but this
        // stops the buffer growing past it in the first place.
        if self.text.len() > MAX_BLOCK_TEXT {
            return;
        }
        let decoded = decode_entities(text);
        if self.text.trim().is_empty() && !decoded.trim().is_empty() {
            if let Some(mark) = self.mark.take() {
                self.synthetic(&mark);
            }
        }
        self.push_span(&decoded);
        if self.pre > 0 {
            // Control characters have no drawing, and the preformatted path
            // does not collapse them away. Tabs and newlines stay: both are
            // the reason this block is preformatted.
            self.text.extend(
                decoded
                    .chars()
                    .filter(|c| *c == '\n' || *c == '\t' || !c.is_control()),
            );
        } else {
            self.text.push_str(&decoded);
        }
    }

    fn push_span(&mut self, text: &str) {
        if text.is_empty() {
            return;
        }
        if let Some(last) = self
            .spans
            .last_mut()
            .filter(|last| last.style == self.inline && last.formula.is_none())
        {
            last.text.push_str(text);
        } else {
            self.spans.push(InlineSpan {
                text: text.to_owned(),
                style: self.inline,
                formula: None,
            });
        }
    }

    /// Writes text the document did not literally contain.
    ///
    /// A line break's space, a table cell's separator, a picture's bracketed
    /// description: each has to reach the styled runs as well as the block
    /// text. If only one of the two receives it the runs stop matching the
    /// block, and `bound_rich_spans` answers that by throwing away every
    /// emphasis the block had.
    fn synthetic(&mut self, text: &str) {
        self.text.push_str(text);
        self.push_span(text);
    }

    #[allow(clippy::too_many_lines)]
    fn open(&mut self, name: &str, inside: &str) {
        // Inside a `<pre>`, nothing but its own end tag changes anything. A
        // listing full of `<` is a listing, and re-flowing it on a stray tag
        // would lose the shape that is the whole point of the element.
        if self.pre > 0 {
            if name == "br" {
                self.synthetic("\n");
            }
            return;
        }
        // Noted before the element is interpreted, because whatever this
        // element becomes is where the name points. A name on an element that
        // turns out to say nothing lands on the block after it, which is the
        // next thing a reader sent there would actually read.
        if let Some(id) = attribute(inside, "id") {
            self.builder.mark_anchor(&decode_entities(id));
        }
        // A footnote is written where it is referred to, and a generator that
        // has no page to put it at the foot of leaves the whole of it sitting
        // in the middle of the sentence. Read straight through, the sentence
        // breaks off after the word the note hangs on, a paragraph of aside
        // runs by, and the sentence resumes. The mark stays where it is; the
        // body is set aside and comes back as its own block after the
        // paragraph, which is where a reader expects to find it.
        if let Some(note) = &mut self.note {
            if note.tag == name {
                note.depth += 1;
            }
        } else if is_a_note_body(inside) || is_a_generators_own_mark(inside) {
            self.note = Some(OpenNote {
                tag: name.to_owned(),
                depth: 0,
                text_from: self.text.len(),
                spans_from: self.spans.len(),
                keep: is_a_note_body(inside),
            });
        }
        if name == "img" {
            // Emitted where it stands, so a picture keeps its place among the
            // paragraphs. The source is left exactly as the book wrote it --
            // resolving it against the file it came from needs to know what
            // that file was, which only the format assembling the book does.
            if let Some(source) = attribute(inside, "src") {
                self.flush();
                let alt = attribute(inside, "alt")
                    .map(decode_entities)
                    .unwrap_or_default();
                self.builder.push(Block::Picture {
                    name: decode_entities(source),
                    alt,
                    illustration: true,
                });
            }
            return;
        }
        if name == "a" {
            // Where the words of the link start, so they can be taken back
            // out when it closes: a link's own text is what a reader taps,
            // and the paragraph around it is not.
            if let Some(href) = attribute(inside, "href") {
                self.link = Some((decode_entities(href), self.text.len()));
            }
            return;
        }
        if matches!(
            name,
            "strong" | "b" | "em" | "i" | "u" | "sup" | "sub" | "span" | "small" | "mark"
        ) {
            self.inline_stack.push((name.to_owned(), self.inline));
            match name {
                "strong" | "b" => self.inline.strong = true,
                "em" | "i" => self.inline.emphasis = true,
                "u" => self.inline.underline = true,
                "sup" => self.inline.superscript = true,
                "sub" => self.inline.subscript = true,
                _ => {}
            }
            let declarations = self.stylesheet.declarations_for(name, inside);
            apply_inline_style(&mut self.inline, Some(&declarations));
            return;
        }
        match name {
            // A `<br>` is a soft break. One column, and the paginator wraps:
            // honouring it would give a ragged short line in the middle of a
            // paragraph.
            "br" => self.synthetic(" "),
            // A picture cannot be drawn inside a run of text, so what it was
            // described as is the only part that can survive. An `<img>` with
            // no description says nothing, and brackets around nothing would
            // be worse than silence.
            "img" | "image" => {
                if let Some(alt) = attribute(inside, "alt").filter(|alt| !alt.trim().is_empty()) {
                    let alt = decode_entities(alt);
                    self.synthetic(" [");
                    self.synthetic(&alt);
                    self.synthetic("] ");
                }
            }
            "hr" => {
                self.flush();
                self.builder.push(Block::Rule);
            }
            "title" => {
                self.flush();
                self.titling = true;
            }
            "meta" => self.read_meta(inside),
            "blockquote" | "q" => {
                self.flush();
                self.quoted += 1;
            }
            "pre" => {
                self.flush();
                self.pre += 1;
            }
            "ul" | "menu" | "dl" => {
                self.flush();
                self.lists.push(false);
            }
            "ol" => {
                self.flush();
                self.lists.push(true);
            }
            "li" | "dd" => {
                self.flush();
                self.item = true;
            }
            "figcaption" => {
                self.flush();
                let declarations = self.stylesheet.declarations_for(name, inside);
                let parent = self.block_style.clone();
                self.block_stack.push((name.to_owned(), parent.clone()));
                self.block_style = block_style_inheriting(&parent, &declarations);
                self.inline_stack.push((name.to_owned(), self.inline));
                apply_inline_style(&mut self.inline, Some(&declarations));
                self.caption = true;
            }
            // A row is one block and a cell is one column of it. Both are
            // needed: a cell alone cannot be laid out, because how wide it is
            // depends on every other cell in its column, and a row alone
            // cannot say where one value ends and the next begins.
            // A numbered equation is a table. `LaTeXML` sets one as a row of
            // cells -- the left side, the right side, and the number off in
            // the margin -- and marks every piece of mathematics in it
            // `display="inline"`, because inside the row it is. Read as the
            // table it is spelled as, a paper's central equation came out as a
            // line of text in a bordered box, in the worst of the written
            // forms: `L_(VQ) =||sg(f)-z||_2^2` with the script capitals as
            // holes, because those live in a block the reading face does not
            // cover. It is a displayed equation and is set as one.
            "table" => {
                self.end_table();
                self.flush();
            }
            "tr" if class_of(inside).contains("ltx_eqn_row") => {
                self.end_row();
                self.flush();
                self.equation = Some(Equation::default());
            }
            "tr" => {
                self.end_row();
                self.flush();
                self.row = Some(Row::default());
            }
            // Inside an equation the cells are the halves of one formula and
            // the margin it is numbered in, none of which is a column of
            // anything.
            "td" | "th" if self.equation.is_some() => {}
            "td" | "th" => {
                // A cell outside any row is a cell in a table written without
                // one, which is common enough in hand-written HTML. It opens
                // a row so that the cells still line up with each other.
                if self.row.is_none() {
                    self.flush();
                    self.row = Some(Row::default());
                }
                self.end_cell();
                let reach = |spelling| {
                    attribute(inside, spelling)
                        .and_then(|value| value.trim().parse::<usize>().ok())
                        .unwrap_or(1)
                        .clamp(1, MAX_CELL_SPAN)
                };
                let (span, down) = (reach("colspan"), reach("rowspan"));
                if let Some(row) = &mut self.row {
                    row.open = true;
                    row.header |= name == "th";
                    row.span = span;
                    row.down = down;
                    row.spanned |= span > 1 || down > 1;
                }
            }
            _ => {
                if let Some(level) = heading_level(name) {
                    self.flush();
                    let declarations = self.stylesheet.declarations_for(name, inside);
                    let parent = self.block_style.clone();
                    self.block_stack.push((name.to_owned(), parent.clone()));
                    self.block_style = block_style_inheriting(&parent, &declarations);
                    self.inline_stack.push((name.to_owned(), self.inline));
                    apply_inline_style(&mut self.inline, Some(&declarations));
                    self.heading = Some(level);
                } else if breaks_a_block(name) {
                    self.flush();
                    let declarations = self.stylesheet.declarations_for(name, inside);
                    let parent = self.block_style.clone();
                    self.block_stack.push((name.to_owned(), parent.clone()));
                    self.block_style = block_style_inheriting(&parent, &declarations);
                    self.inline_stack.push((name.to_owned(), self.inline));
                    apply_inline_style(&mut self.inline, Some(&declarations));
                }
            }
        }
    }

    fn close(&mut self, name: &str) {
        if self.pre > 0 && name != "pre" {
            return;
        }
        // Before the inline stack is unwound, because a footnote is spelt
        // with the same element as the emphasis around it and that branch
        // returns without ever reaching the rest of this.
        if let Some(note) = &mut self.note {
            if note.tag == name {
                if note.depth == 0 {
                    self.end_note();
                } else {
                    note.depth -= 1;
                }
            }
        }
        if name == "a" {
            if let Some((target, from)) = self.link.take() {
                let words = self.text.get(from..).unwrap_or_default().to_owned();
                self.builder.record_link(&words, &target);
            }
            return;
        }
        if let Some(at) = self.inline_stack.iter().rposition(|(open, _)| open == name) {
            if heading_level(name).is_some() || breaks_a_block(name) {
                self.flush();
            }
            let (_, style) = self.inline_stack.remove(at);
            self.inline = style;
            if let Some(at) = self.block_stack.iter().rposition(|(open, _)| open == name) {
                let (_, style) = self.block_stack.remove(at);
                self.block_style = style;
            }
            return;
        }
        match name {
            // Flushed before the depth changes, so the last paragraph of a
            // quotation is still part of it.
            "blockquote" | "q" => {
                self.flush();
                self.quoted = self.quoted.saturating_sub(1);
            }
            "pre" => {
                self.flush();
                self.pre = self.pre.saturating_sub(1);
            }
            "ul" | "ol" | "menu" | "dl" => {
                self.flush();
                self.lists.pop();
            }
            "title" => self.flush(),
            "td" | "th" if self.equation.is_some() => {}
            "td" | "th" => self.end_cell(),
            "tr" => {
                self.end_equation();
                self.end_row();
            }
            // A table that ends with a row still open is a table whose last
            // `</tr>` was never written, which is a page, not a corner.
            "table" | "thead" | "tbody" | "tfoot" => {
                self.end_equation();
                self.end_table();
                self.flush();
            }
            _ => {
                if heading_level(name).is_some() || breaks_a_block(name) {
                    self.flush();
                }
            }
        }
    }

    /// Reads what a `<meta>` says the document is.
    fn read_meta(&mut self, inside: &str) {
        let Some(name) = attribute(inside, "name")
            .or_else(|| attribute(inside, "property"))
            .map(str::to_ascii_lowercase)
        else {
            return;
        };
        let Some(content) = attribute(inside, "content") else {
            return;
        };
        let content = decode_entities(content);
        match name.as_str() {
            "author" | "dc.creator" | "citation_author" | "article:author" => {
                self.builder.set_author(&content);
            }
            "og:title" | "dc.title" | "citation_title" => self.builder.set_title(&content),
            _ => {}
        }
    }

    /// Takes the words collected since the cell opened and makes them a cell.
    ///
    /// A no-op outside a table, and outside a cell inside one: text loose in
    /// a row is markup nobody meant, and it stays where it is so that the
    /// ordinary flush treats it as the stray prose it is.
    fn end_cell(&mut self) {
        let Some(row) = &self.row else {
            return;
        };
        if !row.open {
            return;
        }
        let cell = std::mem::take(&mut self.text);
        self.spans.clear();
        let Some(row) = &mut self.row else { return };
        row.open = false;
        let (span, down) = (row.span.max(1), row.down.max(1));
        row.span = 1;
        row.down = 1;
        // Past whatever a cell above still reaches over. Those columns are
        // spoken for, and a cell written into one of them would sit under the
        // wrong heading for the rest of the table.
        while self
            .covered
            .get(row.cells.len())
            .is_some_and(|rows| *rows > 0)
        {
            if row.cells.len() >= crate::MAX_ROW_CELLS {
                break;
            }
            row.cells.push(String::new());
        }
        let at = row.cells.len();
        if at < crate::MAX_ROW_CELLS {
            row.cells.push(cell);
        }
        // The columns the cell covers besides its own. Kept empty rather than
        // filled with a copy of the heading: a grouped header is written once
        // over its columns in print too, and repeating it would put the same
        // words in three cells of one row.
        for _ in 1..span {
            if row.cells.len() >= crate::MAX_ROW_CELLS {
                break;
            }
            row.cells.push(String::new());
        }
        // And the rows it reaches down over, so the rows below leave its
        // columns free. Counted from here because `end_row` takes one off
        // every column at the end of the row this was written in.
        if down > 1 {
            let last = at.saturating_add(span);
            if self.covered.len() < last {
                self.covered.resize(last, 0);
            }
            for column in at..last {
                self.covered[column] = down;
            }
        }
    }

    /// Takes one piece of the equation being read out of its table.
    ///
    /// `\displaystyle` is dropped from each piece: `LaTeXML` writes it on
    /// every cell because each cell is its own `<math>`, and a formula
    /// assembled from three of them would carry the command three times over.
    /// The renderer is already told to set a displayed formula as one.
    fn equation_piece(&mut self, latex: &str, drawn: &str) {
        let Some(equation) = &mut self.equation else {
            return;
        };
        let piece = decode_entities(latex);
        let piece = piece.trim().trim_start_matches("\\displaystyle").trim();
        if !piece.is_empty() {
            equation.latex.push_str(piece);
        }
        let drawn = drawn.trim();
        if !drawn.is_empty() {
            if !equation.drawn.is_empty() {
                equation.drawn.push(' ');
            }
            equation.drawn.push_str(drawn);
        }
    }

    /// Sets the equation that has been gathered, as a formula on its own line.
    ///
    /// The number is set at the end of the formula rather than dropped. A
    /// paper refers back to its equations by number -- "as shown in (1)" is
    /// the whole reason the number is printed -- and an equation drawn without
    /// one leaves that sentence pointing at nothing a reader can find. It
    /// costs a little width, which a formula already too wide for the column
    /// pays for by being scaled to fit.
    fn end_equation(&mut self) {
        let Some(equation) = self.equation.take() else {
            return;
        };
        let drawn = equation
            .drawn
            .split_whitespace()
            .collect::<Vec<_>>()
            .join(" ");
        let mut latex = equation.latex.trim().to_owned();
        if drawn.is_empty() && latex.is_empty() {
            return;
        }
        // Whatever words were being collected belong to the paragraph in
        // front of the equation rather than to it.
        self.flush();
        let number = equation.number.trim();
        let alt = if number.is_empty() {
            drawn
        } else {
            format!("{drawn}  {number}")
        };
        // Only a plain tag. Anything else is not a number this understands,
        // and handing the typesetter something it cannot parse would lose the
        // whole equation to save its label.
        if !latex.is_empty() && is_equation_tag(number) {
            latex.push_str("\\qquad");
            latex.push_str(number);
        }
        let name = format!("{}{}", crate::FORMULA_PICTURE_PREFIX, self.formulae.len());
        // Past the ceiling the equation keeps its block and its written form
        // and simply never has a picture drawn for it, which is what a formula
        // with nothing to draw it has always looked like.
        if self.allowance.open(self.formulae.len()) && !latex.is_empty() {
            self.formulae.insert(name.clone(), latex);
        }
        self.builder.push(Block::Picture {
            name,
            alt,
            illustration: false,
        });
    }

    /// Takes one row off every column a cell above is still reaching over.
    ///
    /// Called when a row ends, so that a `rowspan="2"` written in one row
    /// covers exactly the one row under it.
    fn age_covers(&mut self) {
        for rows in &mut self.covered {
            *rows = rows.saturating_sub(1);
        }
        while self.covered.last() == Some(&0) {
            self.covered.pop();
        }
    }

    /// Sets a finished row down as a block.
    fn push_row(&mut self, row: Row) {
        if row.cells.is_empty() {
            return;
        }
        self.builder.push(Block::Row {
            header: row.header,
            cells: row.cells,
        });
    }

    /// Sets down a row of groups that never found a row to head.
    ///
    /// A table of one row, or one whose second row is data rather than column
    /// names, keeps the groups as the row they were written as.
    fn end_table(&mut self) {
        self.end_row();
        if let Some(groups) = self.held.take() {
            self.push_row(groups);
        }
        // What one table's cells reached over says nothing about the next
        // table's columns.
        self.covered.clear();
        self.rows_seen = 0;
    }

    /// Closes the row being read and pushes it, if there is one worth pushing.
    fn end_row(&mut self) {
        self.end_cell();
        // No row to end means no row has passed. Both `</tr>` and the `<tr>`
        // after it come through here, and ageing on the second would take two
        // rows off a cell that reached over one.
        let Some(mut row) = self.row.take() else {
            return;
        };
        // A row whose last columns are all reached into from above ends
        // before them, so they are filled in here: a row is as wide as the
        // table rather than as wide as the cells somebody wrote into it.
        while row.cells.len() < self.covered.len()
            && row.cells.len() < crate::MAX_ROW_CELLS
            && self.covered[row.cells.len()] > 0
        {
            row.cells.push(String::new());
        }
        self.age_covers();
        if row.cells.is_empty() {
            return;
        }
        // A table's first row, when its cells reach over their neighbours, is
        // a row of groups rather than of column names. It waits for the row
        // under it and the two are set down as one.
        if self.rows_seen == 0 && row.spanned && self.held.is_none() {
            self.rows_seen += 1;
            self.held = Some(row);
            return;
        }
        if let Some(groups) = self.held.take() {
            if heads_the_row_below(&groups.cells, &row.cells) {
                row = join_headings(groups, row);
            } else {
                self.push_row(groups);
            }
        }
        self.rows_seen += 1;
        self.builder.push(Block::Row {
            header: row.header,
            cells: row.cells,
        });
    }

    /// Takes the footnote body back out of the running text.
    fn end_note(&mut self) {
        let Some(note) = self.note.take() else { return };
        if note.text_from > self.text.len() || note.spans_from > self.spans.len() {
            return;
        }
        let text = self.text.split_off(note.text_from);
        let spans = self.spans.split_off(note.spans_from);
        if !note.keep {
            // A number or a letter is the only name the item has, and the
            // page it is set on draws no numbers of its own, so it leads the
            // item's words instead of being lost. A bullet names nothing.
            let mark = text.trim();
            if mark.chars().any(char::is_alphanumeric) && mark.len() <= MAX_MARK {
                self.mark = Some(format!("{mark} "));
            }
            return;
        }
        if text.trim().is_empty() || self.notes.len() >= MAX_HOISTED_NOTES {
            return;
        }
        self.notes.push((text, spans));
    }

    /// Sets the footnotes lifted out of the paragraph just written.
    fn flush_notes(&mut self) {
        if self.notes.is_empty() || self.row.as_ref().is_some_and(|row| row.open) {
            return;
        }
        let style = self.block_style.clone();
        for (text, spans) in std::mem::take(&mut self.notes) {
            let text = text.split_whitespace().collect::<Vec<_>>().join(" ");
            if text.is_empty() {
                continue;
            }
            // Set as a quotation: an aside, marked off from the argument it
            // hangs on, which is what a footnote is.
            self.builder.push_rich(
                Block::Quote(text),
                RichBlock {
                    spans: normalise_spans(spans),
                    style: style.clone(),
                },
            );
        }
    }

    fn flush(&mut self) {
        self.flush_block();
        self.flush_notes();
    }

    fn flush_block(&mut self) {
        // Inside a cell there is nowhere for a block to go. A cell holding a
        // paragraph, or three, is one cell of a row and not three blocks of
        // prose, so the words are kept where they are and the boundary
        // becomes a space. Without this a `<td><p>...</p></td>` table --
        // which is most of the tables LaTeX generators emit -- would spill
        // one paragraph per cell into the body and lose its columns.
        if self.row.as_ref().is_some_and(|row| row.open) {
            self.heading = None;
            self.item = false;
            self.caption = false;
            self.titling = false;
            if !self.text.is_empty() && !self.text.ends_with(char::is_whitespace) {
                self.text.push(' ');
            }
            return;
        }
        let text = std::mem::take(&mut self.text);
        let spans = normalise_spans(std::mem::take(&mut self.spans));
        let style = self.block_style.clone();
        if std::mem::replace(&mut self.titling, false) {
            self.builder.set_title(&text);
            return;
        }
        if self.pre > 0 {
            self.builder
                .push_rich(Block::Preformatted(text), RichBlock { spans, style });
            return;
        }
        // Nothing was written, so nothing is set -- and what this block was
        // going to be is still waiting to be said. A list item written the way
        // a LaTeX generator writes one, `<li><p>...`, opens the paragraph
        // before a single word has been read, and taking the mark here would
        // set the item as an ordinary paragraph with no bullet at all.
        if text.trim().is_empty() {
            return;
        }
        let heading = self.heading.take();
        let item = std::mem::replace(&mut self.item, false);
        let caption = std::mem::replace(&mut self.caption, false);
        if let Some(level) = heading {
            // A page with no `<title>` is usually still named by the one
            // heading at the top of it.
            if level == 1 {
                self.builder.set_title(&text);
            }
            self.builder
                .push_rich(Block::Heading { level, text }, RichBlock { spans, style });
        } else if caption {
            self.builder
                .push_rich(Block::Caption(text), RichBlock { spans, style });
        } else if item {
            let ordered = self.lists.last().copied().unwrap_or(false);
            self.builder
                .push_rich(Block::Item { ordered, text }, RichBlock { spans, style });
        } else if self.quoted > 0 {
            self.builder
                .push_rich(Block::Quote(text), RichBlock { spans, style });
        } else {
            self.builder
                .push_rich(Block::Paragraph(text), RichBlock { spans, style });
        }
    }

    /// Sets a formula that stands on its own line as a picture of itself.
    ///
    /// Only a displayed formula: one set into a sentence has to sit on the
    /// baseline between two words, and a picture cannot yet do that, so those
    /// stay as the line of text [`kobo_html::math::render`] makes of them.
    ///
    /// The description carried beside the picture is that same line of text
    /// rather than the LaTeX, so a formula whose picture has not arrived yet,
    /// or which nothing will draw, still gets mathematics rather than source.
    ///
    /// Returns whether the formula was taken; `false` leaves it to be read as
    /// text by the caller.
    fn display_formula(&mut self, inside: &str, drawn: &str) -> bool {
        if attribute(inside, "display").is_none_or(|display| display != "block")
            || !self.allowance.open(self.formulae.len())
        {
            return false;
        }
        let Some(latex) = attribute(inside, "alttext") else {
            return false;
        };
        // Whatever words were being collected belong to the paragraph in front
        // of the formula, not to the formula, so they are put down first.
        self.flush();
        let name = format!("{}{}", crate::FORMULA_PICTURE_PREFIX, self.formulae.len());
        self.formulae.insert(name.clone(), decode_entities(latex));
        self.builder.push(Block::Picture {
            name,
            alt: drawn.trim().to_owned(),
            illustration: false,
        });
        true
    }

    /// Sets a formula standing inside a sentence as a picture of itself.
    ///
    /// The run keeps the words [`kobo_html::math::render`] made of it, so the
    /// sentence still reads, still searches and still copies; the picture is
    /// drawn over those words rather than in place of them. A formula that
    /// will not typeset simply is not taken, and the words stand on their
    /// own, which is what happened to every formula before this existed.
    ///
    /// Returns whether the formula was taken.
    fn inline_formula(&mut self, inside: &str, drawn: &str) -> bool {
        if drawn.trim().is_empty() || !self.allowance.open(self.formulae.len()) {
            return false;
        }
        let Some(latex) = attribute(inside, "alttext") else {
            return false;
        };
        if self.text.len() > MAX_BLOCK_TEXT {
            return false;
        }
        let name = format!("{}{}", crate::FORMULA_PICTURE_PREFIX, self.formulae.len());
        self.formulae.insert(name.clone(), decode_entities(latex));
        // The same two steps [`Self::words`] takes, because the words and the
        // styled runs have to stay the same string: a run that does not match
        // the block text costs the block every emphasis it had. Its own run
        // rather than an append, so the formula covers exactly its own words.
        let words = decode_entities(drawn.trim());
        self.text.push_str(&words);
        self.spans.push(InlineSpan {
            text: words,
            style: self.inline,
            formula: Some(name),
        });
        true
    }

    fn finish(mut self) -> Document {
        self.end_row();
        self.flush();
        let formulae = std::mem::take(&mut self.formulae);
        let mut document = self.builder.finish();
        // Joined rather than assigned: a book read a file at a time brings the
        // formulae of every file before this one.
        document.formulae.extend(formulae);
        document
    }
}

#[derive(Clone, Debug, Default)]
struct StyleSheet {
    rules: Vec<CssRule>,
}

#[derive(Clone, Debug)]
struct CssRule {
    selector: String,
    declarations: String,
    specificity: u8,
    order: usize,
}

fn embedded_styles(source: &str) -> String {
    let lower = source.to_ascii_lowercase();
    let mut out = String::new();
    let mut at = 0usize;
    while out.len() < MAX_CSS_BYTES {
        let Some(open) = lower[at..].find("<style") else {
            break;
        };
        let open = at + open;
        let Some(tag_end) = lower[open..].find('>') else {
            break;
        };
        let body = open + tag_end + 1;
        let Some(close) = lower[body..].find("</style") else {
            break;
        };
        let close = body + close;
        let content = &source[body..close];
        let mut take = content.len().min(MAX_CSS_BYTES.saturating_sub(out.len()));
        while !content.is_char_boundary(take) {
            take -= 1;
        }
        out.push_str(&content[..take]);
        at = close + "</style".len();
    }
    out
}

/// At-rules whose body holds further rules rather than declarations.
///
/// Their contents have to be read, not skipped: a publisher that wraps its
/// whole stylesheet in `@media screen` is still styling the book.
const NESTED_AT_RULES: [&str; 5] = ["media", "supports", "document", "layer", "container"];

/// How deeply conditional groups are followed before the rest is ignored.
const MAX_AT_RULE_DEPTH: usize = 4;

/// Removes `/* ... */` comments.
///
/// A brace inside a comment is not a block, and leaving one in desynchronises
/// every rule after it. An unterminated comment runs to the end of the sheet,
/// which is what a browser does with one.
fn strip_css_comments(css: &str) -> String {
    let mut out = String::with_capacity(css.len());
    let mut rest = css;
    while let Some(open) = rest.find("/*") {
        out.push_str(&rest[..open]);
        let after = &rest[open + 2..];
        let Some(close) = after.find("*/") else {
            return out;
        };
        rest = &after[close + 2..];
    }
    out.push_str(rest);
    out
}

/// The byte index of the `}` closing the block that opens at `open`.
fn matching_brace(css: &str, open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (at, character) in css[open..].char_indices() {
        match character {
            '{' => depth += 1,
            '}' => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(open + at);
                }
            }
            _ => {}
        }
    }
    None
}

/// The at-rule keyword `@media screen and (...)` begins with, lowercased.
fn at_rule_keyword(selectors: &str) -> String {
    selectors
        .trim_start_matches('@')
        .chars()
        .take_while(char::is_ascii_alphabetic)
        .collect::<String>()
        .to_ascii_lowercase()
}

impl StyleSheet {
    fn parse(css: &str) -> Self {
        let mut rules = Vec::new();
        collect_rules(&strip_css_comments(css), 0, &mut rules);
        Self { rules }
    }

    fn declarations_for(&self, name: &str, inside: &str) -> String {
        let classes = attribute(inside, "class").unwrap_or_default();
        let id = attribute(inside, "id").unwrap_or_default();
        let mut matched: Vec<&CssRule> = self
            .rules
            .iter()
            .filter(|rule| selector_matches(&rule.selector, name, id, classes))
            .collect();
        matched.sort_by_key(|rule| (rule.specificity, rule.order));
        let mut result = String::new();
        for rule in matched {
            result.push_str(&rule.declarations);
            result.push(';');
        }
        if let Some(inline) = attribute(inside, "style") {
            result.push_str(inline);
        }
        result
    }
}

/// Reads rules from one stylesheet level, following conditional groups.
///
/// Block extents are found by matching braces rather than by the first `}`,
/// so a nested `@media` body cannot leave the scanner pointing into the
/// middle of the sheet and silently discard every rule after it.
fn collect_rules(css: &str, depth: usize, rules: &mut Vec<CssRule>) {
    let mut rest = css;
    while rules.len() < MAX_CSS_RULES {
        let Some(open) = rest.find('{') else { break };
        let selectors = rest[..open].trim();
        let Some(close) = matching_brace(rest, open) else {
            break;
        };
        let body = rest[open + 1..close].trim();
        let tail = &rest[close + 1..];
        if selectors.starts_with('@') {
            // A conditional group wraps ordinary rules, so its body is read at
            // the next level. A flat at-rule such as `@font-face` or `@page`
            // carries declarations this parser has no selector for, and is
            // skipped whole.
            if depth < MAX_AT_RULE_DEPTH
                && NESTED_AT_RULES.contains(&at_rule_keyword(selectors).as_str())
            {
                collect_rules(body, depth + 1, rules);
            }
            rest = tail;
            continue;
        }
        rest = tail;
        if body.is_empty() {
            continue;
        }
        for selector in selectors.split(',') {
            let selector = selector.trim().to_ascii_lowercase();
            if selector.is_empty()
                || selector.contains([' ', '>', '+', '~', '[', ':', '*'])
                || rules.len() >= MAX_CSS_RULES
            {
                continue;
            }
            let specificity = u8::from(selector.contains('#')) * 100
                + u8::try_from(selector.matches('.').count())
                    .unwrap_or(9)
                    .min(9)
                    * 10
                + u8::from(!selector.starts_with(['.', '#']));
            rules.push(CssRule {
                selector,
                declarations: body.to_owned(),
                specificity,
                order: rules.len(),
            });
        }
    }
}

fn selector_matches(selector: &str, name: &str, id: &str, classes: &str) -> bool {
    let tag_end = selector.find(['.', '#']).unwrap_or(selector.len());
    let tag = &selector[..tag_end];
    if !tag.is_empty() && !tag.eq_ignore_ascii_case(name) {
        return false;
    }
    let class_words: Vec<&str> = classes.split_whitespace().collect();
    let mut rest = &selector[tag_end..];
    while !rest.is_empty() {
        let marker = rest.as_bytes()[0];
        rest = &rest[1..];
        let end = rest.find(['.', '#']).unwrap_or(rest.len());
        let value = &rest[..end];
        let matches = match marker {
            b'.' => class_words
                .iter()
                .any(|class| class.eq_ignore_ascii_case(value)),
            b'#' => id.eq_ignore_ascii_case(value),
            _ => false,
        };
        if !matches {
            return false;
        }
        rest = &rest[end..];
    }
    true
}

fn normalise_spans(spans: Vec<InlineSpan>) -> Vec<InlineSpan> {
    let mut out: Vec<InlineSpan> = Vec::new();
    let mut pending_space = false;
    for span in spans {
        let mut text = String::new();
        for character in span.text.chars() {
            if character.is_whitespace() {
                pending_space = !out.is_empty() || !text.is_empty();
                continue;
            }
            if pending_space {
                text.push(' ');
                pending_space = false;
            }
            if !character.is_control() {
                text.push(character);
            }
        }
        if text.is_empty() {
            continue;
        }
        if let Some(last) = out
            .last_mut()
            .filter(|last| last.style == span.style && last.formula.is_none())
            .filter(|_| span.formula.is_none())
        {
            last.text.push_str(&text);
        } else {
            out.push(InlineSpan {
                text,
                style: span.style,
                formula: span.formula,
            });
        }
    }
    out
}

fn declarations(style: Option<&str>) -> impl Iterator<Item = (&str, &str)> {
    style.into_iter().flat_map(|style| {
        style.split(';').filter_map(|declaration| {
            let (name, value) = declaration.split_once(':')?;
            Some((name.trim(), value.trim()))
        })
    })
}

fn apply_inline_style(style: &mut InlineStyle, source: Option<&str>) {
    for (name, value) in declarations(source) {
        match name.to_ascii_lowercase().as_str() {
            "font-weight"
                if value.eq_ignore_ascii_case("bold")
                    || value.parse::<u16>().is_ok_and(|weight| weight >= 600) =>
            {
                style.strong = true;
            }
            "font-style"
                if value.eq_ignore_ascii_case("italic")
                    || value.eq_ignore_ascii_case("oblique") =>
            {
                style.emphasis = true;
            }
            "text-decoration"
                if value
                    .split_whitespace()
                    .any(|word| word.eq_ignore_ascii_case("underline")) =>
            {
                style.underline = true;
            }
            "vertical-align" if value.eq_ignore_ascii_case("super") => style.superscript = true,
            "vertical-align" if value.eq_ignore_ascii_case("sub") => style.subscript = true,
            _ => {}
        }
    }
}

fn block_style_inheriting(parent: &BlockStyle, source: &str) -> BlockStyle {
    let mut style = BlockStyle {
        alignment: parent.alignment,
        line_height_percent: parent.line_height_percent,
        font_family: parent.font_family.clone(),
        ..BlockStyle::default()
    };
    for (name, value) in declarations(Some(source)) {
        match name.to_ascii_lowercase().as_str() {
            "text-align" => {
                style.alignment = match value.to_ascii_lowercase().as_str() {
                    "center" => TextAlignment::Center,
                    "right" | "end" => TextAlignment::End,
                    "justify" => TextAlignment::Justify,
                    _ => TextAlignment::Start,
                };
            }
            "line-height" => {
                if let Some(percent) = percent(value) {
                    style.line_height_percent = percent.clamp(80, 250);
                }
            }
            "margin-top" => style.margin_before_em = em_hundredths(value).unwrap_or(0),
            "margin-bottom" => style.margin_after_em = em_hundredths(value).unwrap_or(0),
            "text-indent" => {
                style.first_line_indent_em = em_hundredths(value)
                    .and_then(|value| i16::try_from(value).ok())
                    .unwrap_or(0);
            }
            "font-family" => {
                let family = value
                    .split(',')
                    .next()
                    .unwrap_or_default()
                    .trim_matches([' ', '\'', '"']);
                if !family.is_empty() && family.len() <= 128 {
                    style.font_family = Some(family.to_owned());
                }
            }
            "page-break-before" | "break-before"
                if value.eq_ignore_ascii_case("always") || value.eq_ignore_ascii_case("page") =>
            {
                style.page_break_before = true;
            }
            "page-break-after" | "break-after"
                if value.eq_ignore_ascii_case("always") || value.eq_ignore_ascii_case("page") =>
            {
                style.page_break_after = true;
            }
            _ => {}
        }
    }
    style
}

#[allow(clippy::cast_possible_truncation)]
fn percent(value: &str) -> Option<u16> {
    if let Some(value) = value.strip_suffix('%') {
        return value.trim().parse().ok();
    }
    let ratio = value.parse::<f32>().ok()?;
    u16::try_from((ratio * 100.0).round() as i32).ok()
}

#[allow(clippy::cast_possible_truncation)]
fn em_hundredths(value: &str) -> Option<u16> {
    let value = value.trim().strip_suffix("em")?.trim();
    let em = value.parse::<f32>().ok()?;
    if !(0.0..=20.0).contains(&em) {
        return None;
    }
    u16::try_from((em * 100.0).round() as i32).ok()
}

fn heading_level(name: &str) -> Option<u8> {
    match name {
        "h1" => Some(1),
        "h2" => Some(2),
        "h3" => Some(3),
        "h4" => Some(4),
        "h5" => Some(5),
        "h6" => Some(6),
        _ => None,
    }
}

/// Whether this element separates what came before it from what follows.
///
/// The list is generous on purpose. Mistaking a container for a paragraph
/// break costs a paragraph break that was going to be there anyway once the
/// contents were laid out; missing one runs a heading into the sentence after
/// it, which is visible on the page.
fn breaks_a_block(name: &str) -> bool {
    matches!(
        name,
        "p" | "div"
            | "section"
            | "article"
            | "header"
            | "footer"
            | "main"
            | "aside"
            | "nav"
            | "body"
            | "html"
            | "head"
            | "hgroup"
            | "figure"
            | "figcaption"
            | "caption"
            | "address"
            | "center"
            | "table"
            | "thead"
            | "tbody"
            | "tfoot"
            | "tr"
            | "dt"
            | "form"
            | "fieldset"
            | "details"
            | "summary"
            | "noscript"
    )
}

